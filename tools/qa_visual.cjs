const {chromium}=require(process.argv[2]||'playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.argv[3]||undefined});
 const context=await browser.newContext({viewport:{width:1440,height:1100}});
 const page=await context.newPage();
 await page.goto(pathToFileURL(path.join(__dirname,'../dist/index.html')).href);
 await page.locator('.lesson-card').first().waitFor();
 await page.screenshot({path:path.join(__dirname,'../qa/desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(350);
 assert.ok(await page.locator('#sidebar').evaluate(el=>el.getBoundingClientRect().right<=1));
 assert.ok(await page.locator('#menu-toggle').isVisible());
 await page.screenshot({path:path.join(__dirname,'../qa/mobile.png'),fullPage:true});
 await page.screenshot({path:path.join(__dirname,'../qa/mobile-viewport.png')});
 await page.locator('#menu-toggle').click();
 await page.waitForTimeout(250);
 assert.ok(await page.locator('#sidebar').evaluate(el=>el.getBoundingClientRect().left===0));
 await page.locator('#sidebar a[href="#progress"]').click();
 await page.waitForTimeout(250);
 await page.setViewportSize({width:1440,height:1100});
 await page.evaluate(()=>location.hash='#source?path=lesson_4%2Fcv_lecture_4.ipynb&cell=22');
 await page.locator('#cell-22').waitFor();
 await page.locator('#cell-22').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(__dirname,'../qa/notebook.png')});
 await page.evaluate(()=>location.hash='#practice?type=multi&lesson=4&count=5');
 await page.locator('#practice-form button[type=submit]').click();
 await page.locator('#answer-form').waitFor();
 await page.screenshot({path:path.join(__dirname,'../qa/question.png')});
 await browser.close();
 console.log('Visual checks passed: settled mobile sidebar, menu navigation, source deep link and quiz.');
})().catch(e=>{console.error(e);process.exit(1)});
